// Helper functions
export const getProvinsiBySlug = (slug: string): Provinsi | undefined => {
  return provinsiList.find(
    (p) =>
      p.seoSlug === slug ||
      p.variations.some((v) => v.toLowerCase() === slug.toLowerCase())
  );
};

export const getProvinsiByName = (name: string): Provinsi | undefined => {
  return provinsiList.find(
    (p) =>
      p.nama.toLowerCase() === name.toLowerCase() ||
      p.variations.some((v) => v.toLowerCase() === name.toLowerCase())
  );
};

export const getKabupatenBySlug = (
  slug: string,
  provinsiId?: string
): Kabupaten | undefined => {
  return kabupatenList.find(
    (k) =>
      (provinsiId === undefined || k.provinsiId === provinsiId) &&
      (k.seoSlug === slug ||
        k.variations.some((v) => v.toLowerCase() === slug.toLowerCase()))
  );
};

export const getKabupatenByName = (
  name: string,
  provinsiId?: string
): Kabupaten | undefined => {
  return kabupatenList.find(
    (k) =>
      (provinsiId === undefined || k.provinsiId === provinsiId) &&
      (k.nama.toLowerCase() === name.toLowerCase() ||
        k.variations.some((v) => v.toLowerCase() === name.toLowerCase()))
  );
};

export const getKabupatenByProvinsi = (provinsiId: string): Kabupaten[] => {
  return kabupatenList.filter((k) => k.provinsiId === provinsiId);
};